// Déclaration d’indépendance du cyberespace — John Perry Barlow.
// Davos, Suisse, 8 février 1996. Traduction française reproduite verbatim depuis
// le fichier fourni ; texte original sur eff.org/cyberspace-independence.

export default function ADeclarationOfTheIndependenceOfCyberspace() {
  return (
    <>
      <p>
        Gouvernements du monde industriel, géants lassés de chair et d’acier, je
        viens du Cyberespace, la nouvelle demeure de l’Esprit. Au nom du futur, je
        demande au passé de nous laisser tranquilles. Vous n’êtes pas les
        bienvenus parmi nous. Vous n’avez aucune souveraineté là où nous nous
        rassemblons.
      </p>
      <p>
        Nous n’avons pas de gouvernement élu, et il est peu probable que nous en
        ayons un ; aussi je m’adresse à vous avec non plus d’autorité que celle
        avec laquelle la liberté elle-même parle toujours. Je déclare que l’espace
        social mondial que nous construisons est naturellement indépendant des
        tyrannies que vous cherchez à nous imposer. Vous n’avez aucun droit moral
        de nous régir, et vous ne possédez aucune méthode de contrainte que nous
        ayons une véritable raison de craindre.
      </p>
      <p>
        Les gouvernements tirent leurs justes pouvoirs du consentement des
        gouvernés. Vous n’avez ni sollicité ni reçu le nôtre. Nous ne vous avons
        pas invités. Vous ne nous connaissez pas, et vous ne connaissez pas notre
        monde. Le Cyberespace ne se situe pas dans vos frontières. Ne croyez pas
        pouvoir le construire comme s’il s’agissait d’un projet de construction
        publique. Vous ne le pouvez pas. C’est un acte de la nature et il se
        développe lui-même grâce à nos actions collectives.
      </p>
      <p>
        Vous n’avez pas pris part à notre grande conversation en cours, et vous
        n’avez pas créé la richesse de nos marchés. Vous ne connaissez ni notre
        culture, ni notre éthique, ni les codes non écrits qui assurent déjà à
        notre société plus d’ordre que n’importe laquelle de vos impositions ne
        pourrait le faire.
      </p>
      <p>
        Vous prétendez qu’il existe parmi nous des problèmes que vous devez
        résoudre. Vous utilisez cet argument comme prétexte pour envahir nos
        domaines. Beaucoup de ces problèmes n’existent pas. Là où il y a de réels
        conflits, là où il y a des torts, nous les identifierons et les
        traiterons par nos propres moyens. Nous forgeons notre propre Contrat
        Social. Cette gouvernance émergera selon les conditions de notre monde,
        pas du vôtre. Notre monde est différent.
      </p>
      <p>
        Le Cyberespace est constitué de transactions, de relations et de la
        pensée elle-même, disposées comme une onde stationnaire dans le tissu de
        nos communications. Notre monde est à la fois partout et nulle part, mais
        ce n’est pas un lieu où vivent les corps.
      </p>
      <p>
        Nous créons un monde que tous peuvent intégrer sans privilège ni préjugé
        accordé par la race, la puissance économique, la force militaire ou le
        rang de naissance.
      </p>
      <p>
        Nous créons un monde où quiconque, où qu’il soit, peut exprimer ses
        croyances, aussi singulières soient-elles, sans craindre d’être contraint
        au silence ou à la conformité.
      </p>
      <p>
        Vos concepts juridiques de propriété, d’expression, d’identité, de
        mouvement et de contexte ne s’appliquent pas à nous. Ils sont tous fondés
        sur la matière, et il n’y a pas de matière ici.
      </p>
      <p>
        Nos identités n’ont pas de corps ; ainsi, contrairement à vous, nous ne
        pouvons obtenir l’ordre par la contrainte physique. Nous croyons que notre
        gouvernance émergera de l’éthique, de l’intérêt personnel éclairé et du
        bien commun. Nos identités peuvent être distribuées à travers nombre de
        vos juridictions. La seule loi que toutes nos cultures constitutives
        reconnaîtraient généralement est la Règle d’Or. Nous espérons pouvoir
        bâtir nos solutions particulières sur cette base. Mais nous ne pouvons
        accepter les solutions que vous tentez d’imposer.
      </p>
      <p>
        Aux États-Unis, vous avez créé aujourd’hui une loi, le Telecommunications
        Reform Act, qui répudie votre propre Constitution et insulte les rêves de
        Jefferson, Washington, Mill, Madison, De Tocqueville et Brandeis. Ces
        rêves doivent maintenant renaître en nous.
      </p>
      <p>
        Vous êtes terrifiés par vos propres enfants, car ils sont natifs d’un
        monde où vous serez toujours des immigrants. Parce que vous les craignez,
        vous confiez à vos bureaucraties les responsabilités parentales que vous
        êtes trop lâches pour assumer vous-mêmes. Dans notre monde, tous les
        sentiments et toutes les expressions de l’humanité, du plus avilissant au
        plus angélique, font partie d’un tout indivisible, la conversation
        mondiale des bits. Nous ne pouvons séparer l’air qui étouffe de l’air sur
        lequel battent les ailes.
      </p>
      <p>
        En Chine, en Allemagne, en France, en Russie, à Singapour, en Italie et
        aux États-Unis, vous essayez de conjurer le virus de la liberté en
        érigeant des postes de garde aux frontières du Cyberespace. Ceux-ci
        pourront peut-être tenir la contagion à l’écart pendant un court moment,
        mais ils ne fonctionneront pas dans un monde qui sera bientôt recouvert de
        médias porteurs de bits.
      </p>
      <p>
        Vos industries de l’information, de plus en plus obsolètes, chercheraient
        à se perpétuer en proposant des lois, en Amérique et ailleurs, qui
        prétendent posséder la parole elle-même à travers le monde. Ces lois
        déclareraient les idées comme étant un autre produit industriel, pas plus
        noble que la fonte de porc. Dans notre monde, tout ce que l’esprit humain
        peut créer peut être reproduit et distribué à l’infini sans coût. Le
        transport mondial de la pensée ne nécessite plus vos usines pour
        s’accomplir.
      </p>
      <p>
        Ces mesures de plus en plus hostiles et coloniales nous placent dans la
        même position que ces amoureux précédents de la liberté et de
        l’autodétermination qui ont dû rejeter l’autorité de puissances lointaines
        et mal informées. Nous devons déclarer nos moi virtuels immunisés contre
        votre souveraineté, même si nous continuons à consentir à votre règne sur
        nos corps. Nous nous répandrons à travers la planète afin que nul ne
        puisse arrêter nos pensées.
      </p>
      <p>
        Nous créerons une civilisation de l’Esprit dans le Cyberespace.
        Puissiez-vous la rendre plus humaine et plus juste que le monde que vos
        gouvernements ont fait auparavant.
      </p>
      <p>
        Davos, Suisse
        <br />
        8 février 1996
      </p>
    </>
  );
}
